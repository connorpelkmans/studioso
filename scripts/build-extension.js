// Builds the Studyboard School Sync browser extension (extension/) for the stores:
//   extension/build/chrome/    unpacked, for Chrome and Edge (Load unpacked to try it)
//   extension/build/firefox/   unpacked, for Firefox (about:debugging, Load Temporary Add-on)
//   extension/dist/studyboard-school-sync-<version>-chrome.zip    upload to the Chrome Web Store and to Microsoft Edge Add-ons
//   extension/dist/studyboard-school-sync-<version>-firefox.zip   upload to addons.mozilla.org (AMO)
//   extension/dist/studyboard-school-sync-<version>-source.zip    AMO asks for the source when a file is generated: this is it, with this script
// Usage: node scripts/build-extension.js   (Node 18 or newer; nothing to install)
// harvest.js is generated from lms.js: the same harvest scripts and result cleaning the desktop app, the phone apps and the website's bookmark use.
// They're put inside a function whose parameters are named fetch and location, so the background can run them with its own fetch that only
// reaches the school's site, and a school tab can run them with the page's own. Nothing is evaluated from text: the stores don't allow it.
const fs = require("fs"), path = require("path"), zlib = require("zlib");
const { loadLms, cleaning } = require("./build-lms-mobile.js");
const root = path.join(__dirname, ".."), SRC = path.join(root, "extension", "src"), OUT = path.join(root, "extension", "build"), DIST = path.join(root, "extension", "dist");
const GECKO_ID = "school-sync@studyboardapp.com";

function harvestJs() {
  const L = loadLms(), lmsSrc = fs.readFileSync(path.join(root, "lms.js"), "utf8");
  const fns = { brightspace: L.bsHarvest, canvas: L.cvHarvest, blackboard: L.bbHarvest };
  for (const [id, f] of Object.entries(fns)) if (typeof f !== "function" || !/^async function \w+\(/.test(f.toString())) throw new Error("build-extension: harvest not found in lms.js: " + id);
  const out = [
    "// GENERATED by `node scripts/build-extension.js` from lms.js (Studyboard's harvest scripts and result cleaning). Don't edit by hand.",
    "// make(fetch, location) gives the three harvests, each reading one school site with the fetch it's given; clean() checks what they return.",
    "globalThis.__studyboardExt = (function () {",
    "  \"use strict\";",
    cleaning(lmsSrc),
    L.HARVEST_PRELUDE,
    "  function make(fetch, location) {",
    Object.values(fns).map(f => f.toString()).join("\n"),
    "    return { brightspace: bsHarvest, canvas: cvHarvest, blackboard: bbHarvest };",
    "  }",
    "  return Object.freeze({ make: make, clean: cleanHarvest, originOf: originOf });",
    "})();",
    ""
  ].join("\n");
  if (/\beval\s*\(|new Function\s*\(/.test(out)) throw new Error("build-extension: harvest.js must not evaluate text");
  return out;
}

function manifests() {
  const base = JSON.parse(fs.readFileSync(path.join(SRC, "manifest.json"), "utf8"));
  const chrome = JSON.parse(JSON.stringify(base));
  const firefox = JSON.parse(JSON.stringify(base));
  delete firefox.minimum_chrome_version;
  firefox.background = { scripts: ["background.js"] };
  firefox.browser_specific_settings = { gecko: {
    id: GECKO_ID, strict_min_version: "140.0",          // 140: the first Firefox that reads data_collection_permissions (AMO requires it)
    // What leaves the extension: the school data it reads goes to the Studyboard web app in this browser (which can sync it to the
    // student's own account). Course content, names and emails of teaching staff, and Canvas Inbox messages.
    data_collection_permissions: { required: ["websiteContent", "personallyIdentifyingInfo", "personalCommunications"] }
  }, gecko_android: { strict_min_version: "142.0" } };
  return { chrome, firefox };
}

const FILES = ["popup.html", "popup.css", "popup.js", "relay.js", "icons/icon-16.png", "icons/icon-32.png", "icons/icon-48.png", "icons/icon-128.png"];
function files(target) {
  const h = harvestJs(), m = manifests()[target];
  const out = { "manifest.json": JSON.stringify(m, null, 2) + "\n", "harvest.js": h,
    // The background is the harvest file followed by background.js, so one file works as Chrome's service worker and Firefox's script.
    "background.js": h + "\n" + fs.readFileSync(path.join(SRC, "background.js"), "utf8") };
  for (const f of FILES) out[f] = fs.readFileSync(path.join(SRC, f));
  return out;
}

// A plain zip (deflate), with fixed dates so the same source always gives the same file
const CRC = (() => { const t = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } return t; })();
const crc32 = b => { let c = 0xFFFFFFFF; for (let i = 0; i < b.length; i++) c = CRC[(c ^ b[i]) & 255] ^ (c >>> 8); return (c ^ 0xFFFFFFFF) >>> 0; };
function zip(entries) {
  const parts = [], central = []; let off = 0;
  const DOS_TIME = 0, DOS_DATE = (2026 - 1980) << 9 | 1 << 5 | 1;
  for (const [name, data0] of Object.entries(entries).sort(([a], [b]) => a < b ? -1 : 1)) {
    const data = Buffer.isBuffer(data0) ? data0 : Buffer.from(data0, "utf8"), nm = Buffer.from(name, "utf8"), comp = zlib.deflateRawSync(data, { level: 9 }), crc = crc32(data);
    const lh = Buffer.alloc(30); lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(0x0800, 6); lh.writeUInt16LE(8, 8); lh.writeUInt16LE(DOS_TIME, 10); lh.writeUInt16LE(DOS_DATE, 12);
    lh.writeUInt32LE(crc, 14); lh.writeUInt32LE(comp.length, 18); lh.writeUInt32LE(data.length, 22); lh.writeUInt16LE(nm.length, 26); lh.writeUInt16LE(0, 28);
    const ch = Buffer.alloc(46); ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(0x0800, 8); ch.writeUInt16LE(8, 10); ch.writeUInt16LE(DOS_TIME, 12); ch.writeUInt16LE(DOS_DATE, 14);
    ch.writeUInt32LE(crc, 16); ch.writeUInt32LE(comp.length, 20); ch.writeUInt32LE(data.length, 24); ch.writeUInt16LE(nm.length, 28); ch.writeUInt32LE(off, 42);
    parts.push(lh, nm, comp); central.push(ch, nm); off += 30 + nm.length + comp.length;
  }
  const cd = Buffer.concat(central), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(central.length / 2, 8); end.writeUInt16LE(central.length / 2, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(off, 16);
  return Buffer.concat(parts.concat([cd, end]));
}

function sourceEntries() {
  const out = {}, add = rel => { out[rel] = fs.readFileSync(path.join(root, rel)); };
  const walk = dir => fs.readdirSync(path.join(root, dir)).forEach(f => { const rel = dir + "/" + f; fs.statSync(path.join(root, rel)).isDirectory() ? walk(rel) : add(rel); });
  walk("extension/src");
  ["extension/README.md", "lms.js", "scripts/build-extension.js", "scripts/build-lms-mobile.js", "LICENSE"].forEach(f => { if (fs.existsSync(path.join(root, f))) add(f); });
  out["BUILD.txt"] = "Studyboard School Sync: how to build the files in the Firefox package from this source\n\n" +
    "1. Install Node.js 18 or newer (no npm packages are needed).\n2. In this folder run:  node scripts/build-extension.js\n" +
    "3. The Firefox package is extension/build/firefox/ (and extension/dist/*-firefox.zip).\n\n" +
    "harvest.js and the top of background.js are generated from lms.js by scripts/build-extension.js, unminified. Every other file is copied as is.\n";
  return out;
}

function build() {
  const version = manifests().chrome.version;
  fs.rmSync(OUT, { recursive: true, force: true }); fs.mkdirSync(DIST, { recursive: true });
  const made = {};
  for (const target of ["chrome", "firefox"]) {
    const fl = files(target);
    for (const [name, data] of Object.entries(fl)) { const f = path.join(OUT, target, name); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, data); }
    const z = path.join(DIST, `studyboard-school-sync-${version}-${target}.zip`); fs.writeFileSync(z, zip(fl)); made[target] = z;
  }
  const s = path.join(DIST, `studyboard-school-sync-${version}-source.zip`); fs.writeFileSync(s, zip(sourceEntries())); made.source = s;
  return { version, made };
}

module.exports = { build, harvestJs, manifests, files, zip };
if (require.main === module) {
  const r = build();
  console.log("Studyboard School Sync " + r.version);
  Object.values(r.made).forEach(f => console.log("  " + path.relative(root, f) + "  (" + Math.round(fs.statSync(f).size / 1024) + " KB)"));
}
