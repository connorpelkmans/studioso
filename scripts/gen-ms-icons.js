#!/usr/bin/env node
// Writes src/js/01-ms-icons.js from Microsoft's own Office app icons in vendor/microsoft-office-icons/ (downloaded unchanged
// from Microsoft's Fluent CDN, under the Microsoft Fabric Assets License; see that folder's README). Each icon goes in as a
// base64 data: URI of the exact file, so it's shown byte for byte as Microsoft made it. tests/ms-icons.test.js checks it.
"use strict";
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, ".."), dir = path.join(root, "vendor", "microsoft-office-icons");
const APPS = {onenote: "onenote", word: "word", excel: "excel", ppt: "powerpoint"};
const uri = f => "data:image/svg+xml;base64," + fs.readFileSync(path.join(dir, f)).toString("base64");
const body = Object.entries(APPS).map(([k, f]) => `  ${k}: {s20: "${uri(f + "_20x1.svg")}", s32: "${uri(f + "_32x1.svg")}"}`).join(",\n");
const out = `/* ===== module: 01-ms-icons.js ===== */
/* GENERATED by \`node scripts/gen-ms-icons.js\` from vendor/microsoft-office-icons/ (Microsoft's own Office app icons, unchanged,
   under the Microsoft Fabric Assets License). Don't edit by hand. Use them only on buttons and links that open or work with that
   Microsoft app, at full color, never altered, cropped, recolored or locked up with text as a logo (see the folder's README). */
const MS_ICON = {
${body}
};
`;
fs.writeFileSync(path.join(root, "src", "js", "01-ms-icons.js"), out);
console.log("gen-ms-icons: wrote src/js/01-ms-icons.js");
