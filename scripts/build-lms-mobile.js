// Builds lms-mobile.js (the phone apps' school site layer) from lms-mobile.src.js and lms.js, so the iPhone and Android apps run the very same
// harvest scripts and result cleaning as the desktop app. Usage: node scripts/build-lms-mobile.js [outFile]   (prepare.js calls build(out))
// Also refreshes the website's bookmark code inside index.html (see buildGrab below): node scripts/build-lms-mobile.js --grab
// And the native plugins' script allowlist (see nativeScripts below): node scripts/build-lms-mobile.js --native
const fs = require("fs"), path = require("path"), Module = require("module"), crypto = require("crypto"), vm = require("vm");
const root = path.join(__dirname, "..");

function loadLms() {
  const realLoad = Module._load;
  Module._load = function (req, ...rest) {
    if (req === "electron") return { app: { isPackaged: true, userAgentFallback: "" }, BrowserWindow: function () {}, ipcMain: { handle() {} }, net: {}, session: {} };
    return realLoad.call(this, req, ...rest);
  };
  try { return require(path.join(root, "lms.js")); } finally { Module._load = realLoad; }
}
// Text of lms.js between two markers (both must exist, so a rename in lms.js fails the build instead of silently shipping a stale copy)
function slice(src, from, to) {
  const a = src.indexOf(from), b = src.indexOf(to, a + 1);
  if (a < 0 || b < 0) throw new Error("build-lms-mobile: marker not found in lms.js: " + (a < 0 ? from : to));
  return src.slice(a, b);
}
// lms.js's origin rules and result cleaning, as plain script text
function cleaning(lmsSrc) {
  const httpsLine = (lmsSrc.match(/^const httpsOnly = .*$/m) || [])[0];
  if (!httpsLine) throw new Error("build-lms-mobile: httpsOnly not found in lms.js");
  return [
    "  // ---- copied from lms.js: origin rules, then result cleaning ----",
    "  var TEST_MODE = false;",
    slice(lmsSrc, "// \"learn.example.edu\"", "// Addresses that are not on the public internet"),
    httpsLine,
    slice(lmsSrc, "const KEY_OK =", "function connect(")
  ].join("\n");
}
// The website's "read it in your browser" bookmark: the website can't sign in to a school site, but the student's own browser already is.
// The page builds a bookmark from these scripts (the same harvest the desktop app runs, with fixed options); clicked on the school's site, it
// reads it there and hands the result back to Studyboard, which cleans it with the same cleanHarvest before anything is used.
// The code is written INTO index.html between the LMS-GRAB markers (not a separate file), so it always ships with the page and a missing or
// stale-cached file can't break the button. Edit lms.js, then run: node scripts/build-lms-mobile.js --grab
const GRAB_SAFE = { pastDays: 60, aheadDays: 240, grades: true, news: true, only: null, skip: [], mail: true };   // (mail: the bookmark also reads the Canvas Inbox)
const GRAB_START = "/* LMS-GRAB-START: generated by `node scripts/build-lms-mobile.js --grab` from lms.js (the Studyboard bookmark's harvest scripts and result cleaning). Don't edit by hand. */";
const GRAB_END = "/* LMS-GRAB-END */";
// The generated block (it sits inside an inline <script>, so it may never contain "</script")
function buildGrab() {
  const L = loadLms(), lmsSrc = fs.readFileSync(path.join(root, "lms.js"), "utf8");
  const harvest = {};
  for (const id of Object.keys(L.P)) harvest[id] = L.harvestScript(L.P[id], GRAB_SAFE);
  const data = JSON.stringify(harvest).replace(/<\//g, "<\\/");
  const out = GRAB_START + "\nconst SBGRAB_BUILT = (function () {\n  \"use strict\";\n" + cleaning(lmsSrc) +
    "\n  return { v: 1, harvest: " + data + ", originOf: originOf, clean: cleanHarvest };\n})();\n" + GRAB_END;
  if (/<\/script/i.test(out)) throw new Error("build-lms-mobile: the bookmark code contains </script");
  return out;
}
// index.html text with a fresh block (or the block as it is now, for the check in tests/lms-grab.e2e.js)
function grabIn(html) {
  const a = html.indexOf("/* LMS-GRAB-START"), b = html.indexOf(GRAB_END, a);
  if (a < 0 || b < 0) throw new Error("build-lms-mobile: LMS-GRAB markers not found in index.html");
  return { now: html.slice(a, b + GRAB_END.length), withFresh: html.slice(0, a) + buildGrab() + html.slice(b + GRAB_END.length) };
}
function build(outFile) {
  const L = loadLms(), lmsSrc = fs.readFileSync(path.join(root, "lms.js"), "utf8"), shim = fs.readFileSync(path.join(root, "lms-mobile.src.js"), "utf8");
  const fromLms = cleaning(lmsSrc);
  const SAFE = "@@SAFE@@", providers = {}, harvest = {}, who = {};
  for (const id of Object.keys(L.P)) {
    const Pv = L.P[id];
    providers[id] = { home: Pv.home, ctx: Pv.ctx };
    harvest[id] = L.harvestScript(Pv, SAFE);
    who[id] = L.WHO[id];
  }
  const scripts = { providers, harvest, who, bsFile: L.BS_FILE("{{ou}}", "{{folder}}", "{{id}}"), cvFile: L.CV_FILE("{{id}}"), mail: `(${L.cvMail.toString()})(${JSON.stringify(SAFE)})` };
  const out = shim.replace("/*@@FROM_LMS_JS@@*/", () => fromLms).replace("/*@@SCRIPTS@@*/null", () => JSON.stringify(scripts));
  if (out.includes("@@FROM_LMS_JS@@") || out.includes("@@SCRIPTS@@")) throw new Error("build-lms-mobile: a placeholder was not filled");
  if (outFile) { fs.mkdirSync(path.dirname(outFile), { recursive: true }); fs.writeFileSync(outFile, out); }
  return out;
}
// ---- The native plugins' allowlist ----
// The phone apps' StudyboardLms plugin runs a script inside the student's signed-in school site. So that a script injected into the app's own page
// (an XSS) can't run whatever it likes there, the plugin only runs the scripts built here: each is fixed text with a few holes. The plugin knows the
// fixed pieces only by UTF-8 byte length and SHA-256, checks every hole (digits; or one JSON value, which it re-writes itself so it can only be data;
// "url" is a JSON string that must start with the school's origin), and runs its own refilled copy. The lists below are generated into
// android-wrapper/.../StudyboardLmsScripts.kt and ios-wrapper/native/StudyboardLmsScripts.swift; tests/lms-mobile.test.js fails when they are stale.
const NATIVE_KT = path.join(root, "android-wrapper", "app", "src", "main", "java", "com", "studioso", "app", "capture", "StudyboardLmsScripts.kt");
const NATIVE_SWIFT = path.join(root, "ios-wrapper", "native", "StudyboardLmsScripts.swift");
// Split `text` at the markers ([marker, kind] pairs) into fixed pieces and holes
function holes(text, marks) {
  const segs = [], kinds = [];
  let rest = text;
  for (;;) {
    let best = null;
    for (const [m, k] of marks) { const i = rest.indexOf(m); if (i >= 0 && (!best || i < best.i)) best = { i, m, k }; }
    if (!best) { segs.push(rest); break; }
    segs.push(rest.slice(0, best.i)); kinds.push(best.k); rest = rest.slice(best.i + best.m.length);
  }
  kinds.forEach((k, i) => {
    if ((k === "json" || k === "url") && i !== kinds.length - 1) throw new Error("build-lms-mobile: a JSON hole must be the last one");
    if (k === "digits" && /^[0-9]/.test(segs[i + 1])) throw new Error("build-lms-mobile: a digits hole is followed by a digit");
  });
  return { segs, kinds };
}
// Every script the page may ask the plugin to run, as {id, use: "who" | "run", segs, kinds}. Mirrors build() and lms-mobile.src.js.
function nativeScripts() {
  const L = loadLms(), shim = fs.readFileSync(path.join(root, "lms-mobile.src.js"), "utf8");
  const SAFE = [JSON.stringify("@@SAFE@@"), "json"], out = [];
  for (const id of Object.keys(L.P)) {
    out.push(Object.assign({ id, use: "who" }, holes(L.WHO[id], [])));
    out.push(Object.assign({ id, use: "run" }, holes(L.harvestScript(L.P[id], "@@SAFE@@"), [SAFE])));
  }
  out.push(Object.assign({ id: "brightspace", use: "run" }, holes(L.BS_FILE("{{ou}}", "{{folder}}", "{{id}}"), [["{{ou}}", "digits"], ["{{folder}}", "digits"], ["{{id}}", "digits"]])));
  out.push(Object.assign({ id: "canvas", use: "run" }, holes(L.CV_FILE("{{id}}"), [["{{id}}", "digits"]])));
  out.push(Object.assign({ id: "canvas", use: "run" }, holes(`(${L.cvMail.toString()})(${JSON.stringify("@@SAFE@@")})`, [SAFE])));
  const fb = shim.match(/var FETCH_B64 = (function \(url\) \{[\s\S]*?\n  \});/);
  if (!fb) throw new Error("build-lms-mobile: FETCH_B64 not found in lms-mobile.src.js");
  out.push(Object.assign({ id: "canvas", use: "run" }, holes(vm.runInNewContext("(" + fb[1] + ")")("@@URL@@"), [[JSON.stringify("@@URL@@"), "url"]])));
  return out;
}
const sha = t => crypto.createHash("sha256").update(t, "utf8").digest("hex");
const nativeHead = "// GENERATED by `node scripts/build-lms-mobile.js --native` from lms.js and lms-mobile.src.js. Don't edit by hand; tests/lms-mobile.test.js checks it.\n" +
  "// The only scripts the StudyboardLms plugin will run in a school site: fixed pieces (UTF-8 byte length + SHA-256) with holes between them.\n";
function nativeFiles() {
  const T = nativeScripts(), q = JSON.stringify;
  const kt = nativeHead + "package com.studioso.app.capture\n\ninternal val LMS_SCRIPTS = arrayOf(\n" + T.map(t =>
    `    LmsScript(${q(t.id)}, ${q(t.use)}, intArrayOf(${t.segs.map(x => Buffer.byteLength(x)).join(", ")}), arrayOf(${t.segs.map(x => q(sha(x))).join(", ")}), arrayOf<String>(${t.kinds.map(q).join(", ")})),\n`).join("") + ")\n";
  const sw = nativeHead + "let sbLmsScripts: [SBLmsScript] = [\n" + T.map(t =>
    `    SBLmsScript(id: ${q(t.id)}, use: ${q(t.use)}, lens: [${t.segs.map(x => Buffer.byteLength(x)).join(", ")}], hashes: [${t.segs.map(x => q(sha(x))).join(", ")}], holes: [${t.kinds.map(q).join(", ")}]),\n`).join("") + "]\n";
  return { [NATIVE_KT]: kt, [NATIVE_SWIFT]: sw };
}
// The plugins' check, in JavaScript (for the tests): the script with its holes checked and refilled, or null when it is not allowed
function nativeCheck(id, use, script, origin, list) {
  const b = Buffer.from(String(script), "utf8");
  for (const t of list || nativeScripts()) {
    if (t.id !== id || t.use !== use) continue;
    const lens = t.segs.map(x => Buffer.byteLength(x)), last = lens.length - 1;
    let pos = 0, out = "", ok = null;
    for (let i = 0; i <= last; i++) {
      if (pos + lens[i] > b.length || sha(b.subarray(pos, pos + lens[i]).toString("utf8")) !== sha(t.segs[i])) break;
      out += b.subarray(pos, pos + lens[i]).toString("utf8"); pos += lens[i];
      if (i === last) { if (pos === b.length) ok = out; break; }
      if (t.kinds[i] === "digits") {
        let j = pos; while (j < b.length && j - pos < 14 && b[j] >= 48 && b[j] <= 57) j++;
        if (j === pos) break; out += b.subarray(pos, j).toString("utf8"); pos = j;
      } else {
        const end = b.length - lens[last]; if (i + 1 !== last || end < pos) break;
        let v; try { v = JSON.parse(b.subarray(pos, end).toString("utf8")); } catch (e) { break; }
        if (t.kinds[i] === "url" && !(typeof v === "string" && v.length <= 4000 && v.startsWith(origin + "/"))) break;
        out += JSON.stringify(v); pos = end;
      }
    }
    if (ok !== null) return ok;
  }
  return null;
}
module.exports = { build, buildGrab, grabIn, nativeScripts, nativeFiles, nativeCheck, loadLms, cleaning };   // loadLms and cleaning: also for scripts/build-extension.js
if (require.main === module) {
  if (process.argv.includes("--grab")) {
    const f = path.join(root, "index.html"), html = fs.readFileSync(f, "utf8");
    let out = grabIn(html).withFresh;
    out = require("./csp").apply(out);
    if (out !== html) { fs.writeFileSync(f, out); console.log("Updated the bookmark code in index.html"); } else console.log("index.html: bookmark code is current");
  }
  else if (process.argv.includes("--native")) {
    for (const [f, text] of Object.entries(nativeFiles())) {
      const now = fs.existsSync(f) ? fs.readFileSync(f, "utf8") : null;
      if (now !== text) { fs.writeFileSync(f, text); console.log("Wrote " + path.relative(root, f)); } else console.log(path.relative(root, f) + " is current");
    }
  }
  else { const f = path.resolve(process.argv[2] || path.join(root, "lms-mobile.js")); build(f); console.log("Wrote " + f); }
}
